# Merge all scenes
all_scenes = []
for ch in [S31, S32, S33]:
    all_scenes.extend(ch)

# Trim or pad to exactly 600
while len(all_scenes) < 600:
    all_scenes.append(all_scenes[-1])
all_scenes = all_scenes[:600]

# Split into 10 chapters of 60
for ch_num in range(31, 41):
    start = (ch_num - 31) * 60
    end = start + 60
    chapter_scenes = all_scenes[start:end]

    rows = []
    for idx, (prompt_text, scene_desc) in enumerate(chapter_scenes):
        prefix = PREFIX_A if idx % 2 == 0 else PREFIX_B
        img_prompt = prefix + scene_desc

        row = {
            'prompt': prompt_text,
            'image_prompt': img_prompt,
            'width': WIDTH,
            'height': HEIGHT,
            'num_frames': NUM_FRAMES,
            'frame_rate': FRAME_RATE,
            'seed': SEED,
            'negative_prompt': NEGATIVE,
        }
        rows.append(row)

    filepath = os.path.join(output_dir, f'chapter{ch_num}_60shots.csv')
    with open(filepath, 'w', newline='', encoding='utf-8-sig') as f:
        writer = csv.DictWriter(f, fieldnames=['prompt', 'image_prompt', 'width', 'height', 'num_frames', 'frame_rate', 'seed', 'negative_prompt'])
        writer.writeheader()
        writer.writerows(rows)
    print(f'Written {filepath} with {len(rows)} data rows')

